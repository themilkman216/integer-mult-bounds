#!/usr/bin/env python3
"""Nominate lenders for the 5 unaliased high helpers and emit extended witnesses.

Simulation in pr2226_replay order (frames only), including witness_43
early_tail_events as incident uses. Lender filters: not removed/lent in
witness_43, not cold-restored there, not incident to an early-tail gate, not
a Y target, not a block helper (592..703), not a centre; last use strictly
before the helper deadline; retirement dimension du <= dim(F1) where F1 is
the helper's first gate frame at/after deadline (emit_word's scan).
Preference: du=4 & final dim 9, then du=4, then du=3 & final 9, then du=3.
Output: witness_48_{base,extra}.json in this package (replay block stale;
regenerated by build48.py). Nothing in research/gmx-t74-borrow43 is modified.
"""
import gzip, json, sys
from pathlib import Path

B = Path('research/gmx-t74-borrow43/new/borrow')
OUT = Path('research/muse-t74-borrow-extend')
sys.path.insert(0, 'research/gmx-t74-borrow43/new/code/borrow')
import bw_gauss  # noqa: E402

def span(basis):
    s = {0}
    for x in basis: s |= {t ^ x for t in list(s)}
    return frozenset(s)
def dim(s): return len(s).bit_length() - 1
def incident(e): return e[1:3] if e[0] == 'add' else e[1:2]
def frame_basis(F):
    b = {}
    for x in F:
        while x:
            j = x.bit_length()
            if j not in b: b[j] = x; break
            x ^= b[j]
    return [b[j] for j in sorted(b, reverse=True)]

MISSING = [606, 635, 637, 638, 639]

def nominate(canon, witname, outname):
    w = json.loads(gzip.decompress((B / 'inputs' / canon).read_bytes()))
    blocks = json.loads((B / 'inputs/blocks.json').read_text())['sources'][0]['blocks']
    wit = json.loads((B / 'inputs' / witname).read_text())
    v, n = w['v'], 2 * w['v'] + w['R']
    frames = list(map(span, w['frames']))
    removed = {p['register'] for p in wit['pairs']}
    lent = {p['borrow_from'] for p in wit['pairs']}
    cold_restored = {c['register'] for c in wit['replay']['exact_cold_restoration']}
    tail_regs = {r for e in wit['early_tail_events'] for r in incident(e['gate'])}
    block_helpers = {h for b in blocks for h in b['helpers']}
    centers = set(w['centers'])
    findim = {r: len(w['frames'][w['final'][r]]) for r in range(n)}
    cur = {r: frames[w['start'][r]] for r in range(n)}
    def climb(e):
        f = frames[e[-1]]
        for r in incident(e): cur[r] = f
    for e in w['precondition'] + w['compensation']: climb(e)
    for e in w['A']: climb(e)
    levels = {r: w['start'][r] for r in range(v, 2 * v)}
    for e in w['precondition'] + w['compensation']:
        for r in incident(e):
            if v <= r < 2 * v: levels[r] = e[-1]
    for r, f in levels.items(): cur[r] = frames[f]
    deferred, skip = {}, set()
    for b in blocks:
        ss, part = set(b['helpers']), []
        for i in range(b['first_correction'], b['first_input']):
            e = w['B'][i]
            if set(incident(e)) <= ss: part.append(e); skip.add(i)
        deferred[b['first_input']] = part
    early_tail = {}
    for e in wit['early_tail_events']: early_tail.setdefault(e['before_B'], []).append(e['gate'])
    dl = {h: next(b['first_input'] for b in blocks if h in b['helpers']) for h in MISSING}
    deadlines = sorted(set(dl.values()))
    snap, last_use, first_frame = {}, {r: -1 for r in range(n)}, {}
    for i, e in enumerate(w['B']):
        if i in deadlines: snap[i] = dict(cur)
        seq = list(early_tail.get(i, [])) + list(deferred.get(i, [])) + ([] if i in skip else [e])
        for g in seq:
            for r in incident(g):
                last_use[r] = i
                if r in dl and i >= dl[r] and r not in first_frame:
                    first_frame[r] = frames[g[-1]]
            climb(g)
    span2frame = {}
    for fi, fr in enumerate(w['frames']): span2frame.setdefault(span(fr), fi)
    used, new_pairs = set(), []
    sib = {}
    for p in wit['pairs']: sib.setdefault(p['base'], p)
    for h in sorted(MISSING, key=lambda x: dl[x]):
        d = dl[h]; F1 = first_frame[h]; fb = frame_basis(F1)
        cand = []
        for L in range(n):
            # tail-incident lenders are allowed: every early-tail gate has
            # before_B <= 863 < deadline, and last_use already counts them.
            if (L in removed or L in lent or L in used or L in cold_restored
                    or L in block_helpers or L in centers
                    or v <= L < 2 * v or L == h): continue
            if last_use[L] >= d: continue
            du = dim(snap[d][L])
            if du == 0 or du > len(fb): continue
            cand.append((L, du, last_use[L]))
        def key(c):
            L, du, _ = c
            return (0 if du == 4 and findim[L] == 9 else 1 if du == 4 else
                    2 if du == 3 and findim[L] == 9 else 3 if du == 3 else 4, L)
        cand.sort(key=key)
        print(outname, 'helper', h, 'deadline', d, 'F1dim', len(fb),
              'filtered candidates', len(cand), 'top', cand[:6])
        assert cand, h
        L, du, lu = cand[0]; used.add(L)
        blk = next(b for b in blocks if h in b['helpers'])
        common = sib[blk['base']]['common_basis'] if blk['base'] in sib else blk['common_frame']
        new_pairs.append(dict(
            register=h, base=blk['base'], common_basis=common,
            dimension=len(common), deadline=d, deleted_echo_indices=[], low=False,
            borrow_from=L, retirement_B_event=lu,
            retirement_frame=span2frame[snap[d][L]], retirement_dimension=du,
            old_final_dimension=9, handoff_B=d, handoff_basis=fb[:du],
            handoff_paid_rank=0, anticipate=False,
            retirement_basis=frame_basis(snap[d][L])))
    ext = json.loads(json.dumps(wit))
    ext['variant'] = '48_' + outname
    ext['pairs'] = wit['pairs'] + new_pairs
    recs = {r['operator']: r for r in ext['gaussian']['records']}
    for k, p in enumerate(new_pairs):
        op = len(wit['pairs']) + k + 1
        recs[op] = dict(operator=op,
                        G_columns=bw_gauss.change(p['retirement_basis'], p['handoff_basis'], 9),
                        handoff_exact_monomial_sha256=None,
                        full_exit_exact_monomial_sha256=None)
    ext['gaussian']['records'] = [recs[i] for i in sorted(recs)]
    ext['gaussian']['operators'] = len(recs)
    (OUT / f'witness_48_{outname}.json').write_text(json.dumps(ext, indent=1) + '\n')
    print('wrote', f'witness_48_{outname}.json', 'new pairs',
          [(p['register'], p['borrow_from'], p['retirement_dimension']) for p in new_pairs])

nominate('gauge44.canonical.json.gz', 'witness_43_base.json', 'base')
nominate('extra.canonical.json.gz', 'witness_43_extra.json', 'extra')
